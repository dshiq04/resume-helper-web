const dictionaries: Record<Lang, Record<string, string>> = {
  "zh-CN": zh,
  "zh-TW": zhTW,
  en,
  ja,
  ko,
  ru,
};

const ANTD_LOCALES: Record<Lang, Locale> = {
  "zh-CN": zhCN,
  "zh-TW": zhTWLocale,
  en: enUS,
  ja: jaJP,
  ko: koKR,
  ru: ruRU,
};

const DAYJS_LOCALES: Record<Lang, string> = {
  "zh-CN": "zh-cn",
  "zh-TW": "zh-tw",
  en: "en",
  ja: "ja",
  ko: "ko",
  ru: "ru",
};

export const LANGUAGES: { value: Lang; label: string }[] = [
  { value: "zh-CN", label: "简体中文" },
  { value: "zh-TW", label: "繁體中文" },
  { value: "en", label: "English" },
  { value: "ja", label: "日本語" },
  { value: "ko", label: "한국어" },
  { value: "ru", label: "Русский" },
];

function isLang(value: string | null): value is Lang {
  return value === "zh-CN" || value === "zh-TW"
    || value === "en" || value === "ja" || value === "ko" || value === "ru";
}

const DEFAULT_LANG: Lang = (() => {
  const value = import.meta.env.VITE_APP_DEFAULT_LANGUAGE;
  return isLang(value) ? value : "zh-CN";
})();

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  antdLocale: Locale;
}

const I18nContext = createContext<I18nValue | null>(null);
const LANG_KEY = "jobtrack.lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem(LANG_KEY);
    return isLang(saved) ? saved : DEFAULT_LANG;
  });

  useEffect(() => {
    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
    // Ant Design 的日期组件依赖 dayjs locale，切换语言时同步更新。
    dayjs.locale(DAYJS_LOCALES[lang]);
  }, [lang]);

  const setLang = useCallback((value: Lang) => setLangState(value), []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>) => {
      let text = dictionaries[lang][key] ?? dictionaries["zh-CN"][key] ?? dictionaries.en[key] ?? key;
      if (params) {
        for (const [name, value] of Object.entries(params)) {
          text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
        }
      }
      return text;
    },
    [lang],
  );

  const value = useMemo<I18nValue>(
    () => ({ lang, setLang, t, antdLocale: ANTD_LOCALES[lang] }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}
